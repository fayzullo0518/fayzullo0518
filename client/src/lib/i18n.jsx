const I18nContext = createContext({
  lang: 'uz',
  setLang: () => {},
  t: (k) => k,
  tr: (k, fallback) => fallback,
  tVal: (v) => v,
  tCat: (c) => c?.name || '',
  tCatTag: (c) => c?.tagline || '',
});

function initialLang() {
  if (typeof window === 'undefined') return 'uz';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (DICTS[stored]) return stored;
  const nav = (window.navigator.language || '').slice(0, 2).toLowerCase();
  if (nav === 'ru') return 'ru';
  if (nav === 'en') return 'en';
  return 'uz';
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* storage may be blocked — the language still applies for this session */
    }
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      let value = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          value = value.split(`{${k}}`).join(String(v));
        }
      }
      return value;
    },
    [lang],
  );

  /** translate, but fall back to `fallback` when the key is unknown */
  const tr = useCallback(
    (key, fallback, vars) => {
      const dict = DICTS[lang] || DICTS.en;
      if (!(key in dict) && !(key in DICTS.en)) return fallback;
      return t(key, vars);
    },
    [lang, t],
  );

  /** a stored catalogue value (lead time, warranty, availability) */
  const tVal = useCallback((value) => (value ? tr(`val.${value}`, value) : ''), [tr]);

  /** catalogue name / tagline, translated when it is one of the imported twelve */
  const tCat = useCallback((c) => (c ? tr(`catName.${c.id}`, c.name) : ''), [tr]);
  const tCatTag = useCallback((c) => (c ? tr(`catTag.${c.id}`, c.tagline || '') : ''), [tr]);

  const value = useMemo(
    () => ({ lang, setLang, t, tr, tVal, tCat, tCatTag }),
    [lang, t, tr, tVal, tCat, tCatTag],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
