function slugSpecs(str) {
  if (!str) return [];
  return str
    .split(';')
    .map((chunk) => chunk.trim())
    .filter(Boolean)
    .map((chunk) => {
      const [label, ...rest] = chunk.split('|');
      return { label: label.trim(), value: rest.join('|').trim() };
    });
}

